/**
 * Generates structured, conventional pull request title and markdown body
 */
export function generatePRDescription({ plan, issueNumber, issueTitle, repoOwner, repoName }) {
  const prTitle = plan.suggestedPR?.title || `fix: resolve ${issueTitle || `issue #${issueNumber}`}`;

  const filesList = (plan.relevantFiles || [])
    .map((f) => `- \`${f.filePath}\` (${f.isVerified ? 'verified' : 'proposed'}): ${f.reason}`)
    .join('\n');

  const stepsList = (plan.implementationSteps || [])
    .map((s) => `${s.stepNumber}. **${s.title}**: ${s.description}`)
    .join('\n');

  const criteriaList = (plan.acceptanceCriteria || [])
    .map((c) => `- [ ] ${c}`)
    .join('\n');

  const testList = (plan.testPlan || [])
    .map((t) => `- [ ] ${t}`)
    .join('\n');

  const markdownBody = `## Summary
Closes ${issueNumber ? `#${issueNumber}` : 'the reported issue'}.
${plan.issueSummary || ''}

### Problem Interpretation
${plan.problemInterpretation || 'Address the root cause described in the linked issue.'}

### Changes Implemented
${stepsList || '- Implemented required changes according to contribution plan.'}

### Modified Files
${filesList || '- See Git diff'}

### Testing & Verification
${testList || '- [ ] Automated tests passing\n- [ ] Manual verification completed'}

### Acceptance Criteria
${criteriaList || '- [ ] Requirements met without regression'}

---
*Generated by [PRPath](https://github.com/prpath) — AI-assisted open-source contribution workflow.*
*Note: Always review changes carefully before submitting.*`;

  return {
    title: prTitle,
    body: markdownBody,
  };
}
